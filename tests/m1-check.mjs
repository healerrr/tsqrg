import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--use-angle=swiftshader','--enable-webgl']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/');
await page.locator('canvas').waitFor();
await page.waitForTimeout(1800);
await mkdir('artifacts/m1',{recursive:true});
await page.screenshot({path:'artifacts/m1/tank-desktop.png'});
await page.keyboard.down('KeyD');await page.waitForTimeout(600);await page.keyboard.up('KeyD');
await page.keyboard.press('Space');await page.waitForTimeout(150);
await page.screenshot({path:'artifacts/m1/dash-desktop.png'});
await page.getByRole('button',{name:'我的鱼',exact:true}).click();
await page.getByRole('button',{name:'河豚 耐打'}).click();
await page.screenshot({path:'artifacts/m1/fish-panel.png'});
await page.keyboard.press('Escape');
await page.setViewportSize({width:844,height:390});await page.waitForTimeout(400);
await page.screenshot({path:'artifacts/m1/tank-mobile-landscape.png'});
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(400);
await page.screenshot({path:'artifacts/m1/tank-mobile-portrait.png'});
await writeFile('artifacts/m1/browser.json',JSON.stringify({browser:await browser.version(),errors,viewports:['1440x900','844x390','390x844']},null,2));
await browser.close();
if(errors.length)throw new Error(errors.join('\n'));
console.log('M1 browser smoke passed; screenshots in artifacts/m1');
